import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('SQL migration: tenant isolation, atomic scheduling and message lifecycle', async t => {
  const db = new PGlite();
  t.after(() => db.close());
  await db.exec(`set timezone = 'America/Sao_Paulo'; create role anon; create role authenticated;
    create schema auth; create table auth.users (id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth,public to authenticated,anon;
    grant execute on function auth.uid() to authenticated,anon;`);
  await db.exec(await readFile(new URL('../supabase/migrations/202609290001_initial.sql',import.meta.url),'utf8'));
  const a='11111111-1111-4111-8111-111111111111', b='22222222-2222-4222-8222-222222222222';
  await db.query('insert into auth.users values ($1),($2)',[a,b]);
  async function login(id) {await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role authenticated');}
  await login(a);
  await db.query('insert into public.professionals(id,full_name,whatsapp_number) values ($1,$2,$3)',[a,'Ana','+5511999991000']);
  const created = await db.query("select public.create_client('Maria','+5511999992000','Limpeza',current_date-30,15,'{}') as id");
  const client = created.rows[0].id;
  let messages = (await db.query('select * from messages')).rows;
  assert.equal(messages.length,1);assert.equal(messages[0].status,'pending');
  const first=messages[0].id;
  const schedule=(await db.query("select scheduled_at = ((current_date-15 + time '09:00') at time zone 'America/Sao_Paulo') as correct from messages")).rows[0];assert.ok(schedule.correct);
  await assert.rejects(db.query("select public.create_client('Outra Maria','+5511999992000','',current_date,15,'{}')"),/unique/i);
  await assert.rejects(db.query("select public.create_client('Invalid','+5511999992222','',current_date,0,'{}')"),/check constraint/i);
  assert.equal((await db.query('select count(*)::int as n from clients')).rows[0].n,1,'invalid interval rolls back client');
  await db.query("select public.record_appointment($1,'Novo atendimento',current_date-1,7)",[client]);
  messages=(await db.query('select * from messages')).rows;
  assert.equal(messages.filter(m=>m.status==='pending').length,1);assert.equal(messages.find(m=>m.id===first).status,'cancelled');
  const active=messages.find(m=>m.status==='pending').id;
  await assert.rejects(db.query("select public.update_pending_message($1,'send')",[first]),/no longer pending/);
  await db.query("select public.update_pending_message($1,'reschedule',null,now()+interval '10 days')",[active]);
  await db.query("select public.update_pending_message($1,'edit','Olá novamente!')",[active]);
  assert.equal((await db.query('select count(*)::int as n from messages')).rows[0].n,2,'rescheduling creates no extra message');
  await assert.rejects(db.query("update messages set status='sent' where id=$1",[active]),/permission denied/);
  await login(b);
  assert.equal((await db.query('select * from clients')).rows.length,0);
  assert.equal((await db.query('select * from client_anamneses')).rows.length,0);
  assert.equal((await db.query('select * from appointments')).rows.length,0);
  assert.equal((await db.query('select * from messages')).rows.length,0);
  await assert.rejects(db.query("select public.record_appointment($1,'Invasão',current_date-1,7)",[client]),/not available/);
  await assert.rejects(db.query("select public.update_pending_message($1,'send')",[active]),/not available/);
  await db.query('insert into public.professionals(id,full_name,whatsapp_number) values ($1,$2,$3)',[b,'Bia','+5511999991001']);
  await db.query("select public.create_client('Maria','+5511999992000','',current_date-1,15,'{}')");
  assert.equal((await db.query('select count(*)::int as n from clients')).rows[0].n,1,'same number permitted in another account');
  await assert.rejects(db.query('insert into clients(professional_id,full_name,whatsapp_number) values ($1,$2,$3)',[a,'Fake','+5511999999999']),/row-level security/);
  const foreignClient = '33333333-3333-4333-8333-333333333333';
  await login(a);
  await db.query('insert into clients(id,full_name,whatsapp_number) values ($1,$2,$3)',[foreignClient,'Sem ficha','+5511999993333']);
  await login(b);
  await assert.rejects(db.query("insert into client_anamneses(client_id, professional_id) values ($1,$2)",[foreignClient,b]),/foreign key/);
  await login(a);
  await db.query("select public.update_pending_message($1,'send')",[active]);
  const sent=(await db.query('select * from messages where id=$1',[active])).rows[0];assert.equal(sent.status,'sent');assert.ok(sent.sent_at);
  await assert.rejects(db.query("select public.update_pending_message($1,'send')",[active]),/no longer pending/);
  await db.exec('reset role; set role anon');
  await assert.rejects(db.query('select * from clients'),/permission denied/);
  await assert.rejects(db.query("select public.record_appointment($1,'',current_date-1,7)",[client]),/permission denied/);
});
